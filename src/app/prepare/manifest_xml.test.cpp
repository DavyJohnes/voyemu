int main() {
    try {
        for (const auto &item : vectors()) {
            const auto input = decode(item.before), snapshot = input;
            auto output = append_manifest_declarations(input, item.names, item.kind);
            check(output == decode(item.after), "native result equals independent TS bytes");
            check(input == snapshot, "input remains immutable");
            bool duplicate = false;
            try {
                append_manifest_declarations(output, {item.names.front()}, item.kind);
            } catch (...) {
                duplicate = true;
            }

            check(duplicate, "duplicate declaration rejected");
        }

        const auto input = decode(vectors().front().before);

        for (const auto &names :
             std::vector<std::vector<std::string>>{{}, {"QGAPI", "QGAPI"}, {"../escape"}, {""}}) {
            bool rejected = false;
            try {
                append_manifest_declarations(input, names, ManifestDeclaration::library);
            } catch (...) {
                rejected = true;
            }

            check(rejected, "invalid library contract rejected");
        }

        for (unsigned mode = 0; mode < 5; ++mode) {
            auto damaged = input;

            if (mode == 0) {
                damaged.resize(damaged.size() - 1);
            }

            if (mode == 1) {
                damaged[24] = 0, damaged[25] = 1;
            }

            if (mode == 2) {
                for (unsigned i = 0; i < 4; ++i) {
                    damaged[12 + i] = 0;
                }
            }

            if (mode == 3) {
                for (unsigned i = 0; i < 4; ++i) {
                    damaged[16 + i] = char(0xff);
                }
            }

            if (mode == 4) {
                for (unsigned i = 0; i < 4; ++i) {
                    damaged[damaged.size() - 4 + i] = char(0xff);
                }
            }

            bool rejected = false;
            try {
                append_manifest_declarations(damaged, {"QGAPI"}, ManifestDeclaration::library);
            } catch (...) {
                rejected = true;
            }

            check(rejected,
                  "truncation UTF8 pool zero chunk count overflow and bad node index rejected");
        }

        bool missing_export = false;
        try {
            append_manifest_declarations(input, {"sample.Service"}, ManifestDeclaration::service);
        } catch (...) {
            missing_export = true;
        }

        check(missing_export, "service requires existing exported resource ID");
        bool long_name = false;
        try {
            append_manifest_declarations(decode(vectors()[2].before),
                                         {"sample." + std::string(32768, 'A')},
                                         ManifestDeclaration::service);
        } catch (...) {
            long_name = true;
        }

        check(long_name, "unsupported UTF16 string length rejected");
        std::cout << "native manifest libraries/services match independent vectors\n";

        return 0;
    } catch (const std::exception &e) {
        std::cerr << e.what() << '\n';

        return 1;
    }
}
