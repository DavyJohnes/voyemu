package com.voyemu.prepare;

import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.HashSet;
import java.util.HexFormat;
import java.util.List;
import java.util.Map;
import java.util.StringJoiner;

/** Generates the native dispatch from the QGFX protocol metadata. */
public final class GenerateGraphics {
    // The profile copy changed serialization while the wire ABI kept its identity.
    private static final String WIRE_CATALOG_PIN =
            "255335b86bb5fd782d23086018dcfc3874d088364ad5f15b264cfb12020d800e";

    public static void main(String[] args) throws Exception {
        var options = new java.util.HashMap<String, Path>();

        if (args.length != 8) {
            throw new IllegalArgumentException("Expected --api, --uniforms, --catalog and --out");
        }

        for (int i = 0; i < args.length; i += 2) {
            String name = args[i];

            if (!List.of("--api", "--uniforms", "--catalog", "--out").contains(name)
                    || options.putIfAbsent(name, Path.of(args[i + 1])) != null) {
                throw new IllegalArgumentException("Unexpected or repeated option: " + name);
            }
        }

        byte[] uniforms = Files.readAllBytes(options.get("--uniforms"));
        String output =
                generate(
                        read(Files.readAllBytes(options.get("--api"))),
                        read(uniforms),
                        MessageDigest.getInstance("SHA-256").digest(uniforms),
                        read(Files.readAllBytes(options.get("--catalog"))));
        Files.writeString(options.get("--out"), output);
    }

    private static Map<String, Object> read(byte[] raw) throws Exception {
        return Json.object(Json.parse(new String(raw, StandardCharsets.UTF_8)));
    }

    private static String generate(
            Map<String, Object> api,
            Map<String, Object> uniforms,
            byte[] uniformsDigest,
            Map<String, Object> catalog) {
        var output =
                new StringBuilder(
                        "// Generated by GenerateGraphics.java from the QGFX protocol metadata; do"
                                + " not edit.\n"
                                + "static constexpr GeneratedSpec generated_specs[] = {\n");
        var functions = Json.list(api.get("functions")).stream().map(Json::object).toList();

        require(functions.size() == 96, "Generated opcode ABI");

        for (int i = 0; i < functions.size(); i++) {
            var function = functions.get(i);
            long opcode = Json.integer(function, "opcode");
            String category = Json.str(function, "category");
            var pointers = Json.list(function.get("pointer_indices"));
            require(opcode == 100 + i, "Generated opcode ABI");
            require(
                    pointers.size() <= 1
                            || category.equals("special")
                            || category.equals("unsupported"),
                    "Unsupported multiple pointer contract");
            output.append('{')
                    .append(opcode)
                    .append(',')
                    .append(Json.write(Json.str(function, "name")))
                    .append(',')
                    .append(Json.write(category))
                    .append(',')
                    .append(Json.list(function.get("params")).size())
                    .append(',')
                    .append(pointers.isEmpty() ? -1 : pointers.get(pointers.size() - 1))
                    .append(',')
                    .append(Json.str(function, "return").equals("void"))
                    .append("},\n");
        }

        output.append("};\nstatic constexpr const char* uniform_names[] = {\n");
        var names = Json.list(uniforms.get("names_hex"));
        require(!names.isEmpty() && names.size() <= 512, "Uniform names geometry");

        for (Object name : names) {
            byte[] bytes = HexFormat.of().parseHex((String) name);
            require(bytes.length > 0 && bytes.length <= 128, "Uniform names geometry");

            for (byte item : bytes) {
                require(item > 0, "Uniform names must be nonzero ASCII");
            }

            output.append(Json.write(new String(bytes, StandardCharsets.US_ASCII))).append(",\n");
        }

        long uniformSchema =
                ByteBuffer.wrap(uniformsDigest).order(ByteOrder.LITTLE_ENDIAN).getLong();
        output.append("};\nstatic constexpr std::uint64_t uniform_schema = ")
                .append(Long.toUnsignedString(uniformSchema))
                .append("ULL;\nstatic constexpr const char* catalog_pin = ")
                .append(Json.write(WIRE_CATALOG_PIN))
                .append(";\nstatic constexpr FieldSpec field_specs[] = {\n");

        var fields = Json.list(catalog.get("fields")).stream().map(Json::object).toList();
        var fieldNames = new HashSet<String>();
        require(fields.size() == 579, "Complete MCU catalog ABI");

        for (int i = 0; i < fields.size(); i++) {
            var field = fields.get(i);
            String name = Json.str(field, "name");
            require(
                    Json.integer(field, "index") == i + 1 && fieldNames.add(name),
                    "Complete MCU catalog ABI");
            output.append('{')
                    .append(Json.write(name))
                    .append(',')
                    .append(Json.integer(field, "width"))
                    .append("},\n");
        }

        output.append(
                "};\n"
                    + "std::uint64_t GeneratedInvoker::invoke(std::uint32_t op, const Arguments&"
                    + " values) {\n"
                    + "switch(op) {\n");

        for (var function : functions) {
            String result = Json.str(function, "return");
            var types = new StringJoiner(",");
            var conversions = new StringJoiner(",");
            var params = Json.list(function.get("params"));

            for (int i = 0; i < params.size(); i++) {
                String type = Json.str(Json.object(params.get(i)), "type");
                types.add(type);
                String value = "(values[" + i + "])";
                String conversion =
                        type.contains("*")
                                ? "reinterpret_cast<" + type + ">"
                                : switch (type) {
                                    case "GLfloat" -> "float_bits";
                                    case "GLint", "GLsizei" -> "signed_bits";
                                    default -> "static_cast<" + type + ">";
                                };
                conversions.add(conversion + value);
            }

            output.append("case ")
                    .append(Json.integer(function, "opcode"))
                    .append(": {\nusing Fn = ")
                    .append(result)
                    .append(" (GL_CALL *)(")
                    .append(types)
                    .append(");\nauto f = symbol<Fn>(")
                    .append(Json.write(Json.str(function, "name")))
                    .append(");\n");
            String call = "f(" + conversions + ")";
            output.append(
                            result.equals("void")
                                    ? call + "; return 0;"
                                    : "return encode_result(" + call + ");")
                    .append("\n}\n");
        }

        return output.append(
                        """
                        default: throw std::runtime_error("Unsupported generated opcode");
                        }
                        }
                        """)
                .toString();
    }

    private static void require(boolean condition, String message) {
        if (!condition) {
            throw new IllegalArgumentException(message);
        }
    }
}
